/**
 * build-tokens.js
 * 
 * Converts Figma / Style Dictionary design tokens (`design-tokens.tokens.json`)
 * into standard CSS custom properties (variables) with full support for:
 * 1. Primitive Colors (Private palette layer - raw values, not used directly on UI)
 * 2. Color Roles (Semantic layer - public tokens used across all UI screens and components)
 * 3. Typography (Material Design 3 type scales & utility classes)
 * 4. Elevation Shadows (Soft, medium, hard effect tokens)
 * 
 * Source of truth: design-tokens.tokens.json
 */

const fs = require('fs');
const path = require('path');

/**
 * Format a color value:
 * If an 8-character hex has 'ff' alpha (100% opacity), simplify to 6-character hex.
 * Otherwise preserve the 8-character hex.
 */
function formatColorValue(hex) {
  if (typeof hex !== 'string') return hex;
  const trimmed = hex.trim().toLowerCase();
  if (/^#[0-9a-f]{8}$/.test(trimmed) && trimmed.endsWith('ff')) {
    return trimmed.slice(0, 7);
  }
  return trimmed;
}

/**
 * Build a clean kebab-case CSS variable name for a primitive color token.
 * Examples:
 * - category: 'primary', key: 'primary40' -> '--primitive-primary-40'
 * - category: 'neutral variant', key: 'neutral variant90' -> '--primitive-neutral-variant-90'
 * - category: 'neutral variant', key: 'neutral100' -> '--primitive-neutral-variant-100'
 * - category: 'key colours', key: 'primary key colour' -> '--primitive-key-primary'
 */
function buildPrimitiveVarName(category, key) {
  const catSlug = category.toLowerCase().trim().replace(/\s+/g, '-');
  const keySlug = key.toLowerCase().trim().replace(/\s+/g, '-');

  if (catSlug === 'key-colours') {
    const name = keySlug.replace(/-?key-?colou?r/, '').trim().replace(/^-+|-+$/g, '');
    return `--primitive-key-${name}`;
  }

  const toneMatch = keySlug.match(/\d+$/);
  if (toneMatch) {
    return `--primitive-${catSlug}-${toneMatch[0]}`;
  }

  return `--primitive-${catSlug}-${keySlug}`;
}

/**
 * Build a clean kebab-case CSS variable name for a semantic color role.
 * Examples:
 * - 'primary' -> '--color-primary'
 * - 'on primary' -> '--color-on-primary'
 * - 'surface container highest' -> '--color-surface-container-highest'
 */
function buildRoleVarName(roleName) {
  const slug = roleName.toLowerCase().trim().replace(/\s+/g, '-');
  return `--color-${slug}`;
}

/**
 * Converts design tokens JSON object into CSS text.
 */
function convertTokensToCSS(tokens) {
  const lines = [];

  // 1. File Header
  lines.push('/**',
    ' * ============================================================================== *',
    ' * DESIGN SYSTEM TOKENS - CSS CUSTOM PROPERTIES                                   *',
    ' *                                                                                *',
    ' * AUTOMATICALLY GENERATED FROM design-tokens.tokens.json                         *',
    ' * DO NOT EDIT THIS FILE DIRECTLY.                                                *',
    ' * To update styles, edit design-tokens.tokens.json and re-run this script.       *',
    ' *                                                                                *',
    ' * STANDARD SYSTEM PRACTICE & USAGE RULES:                                        *',
    ' * ------------------------------------------------------------------------------ *',
    ' * 1. PRIMITIVE COLORS (--primitive-*):                                           *',
    ' *    - Internal / Private palette tier.                                          *',
    ' *    - DO NOT USE DIRECTLY IN UI COMPONENTS OR SCREENS.                          *',
    ' *    - Used exclusively to back the semantic color roles below.                  *',
    ' *                                                                                *',
    ' * 2. COLOR ROLES (--color-*, --color-role-*):                                    *',
    ' *    - Public Semantic / Component tier (Material Design 3 role model).          *',
    ' *    - ALWAYS USE THESE DIRECTLY ON THE UI.                                      *',
    ' *    - Examples: background: var(--color-surface);                               *',
    ' *                color: var(--color-on-surface);                                 *',
    ' *                border-color: var(--color-outline);                             *',
    ' *                                                                                *',
    ' * 3. TYPOGRAPHY (--typography-* & .text-*):                                      *',
    ' *    - Display, Headline, Title, Body, Label (large, medium, small).             *',
    ' *                                                                                *',
    ' * 4. ELEVATION SHADOWS (--shadow-*):                                             *',
    ' *    - Soft, medium, and hard drop-shadows.                                      *',
    ' * ============================================================================== *',
    ' */',
    '',
    ':root {'
  );

  // 2. Index Primitives
  const primitiveMap = new Map(); // jsonPath -> varName
  const primitiveDefs = [];       // { category, key, varName, value }

  if (tokens.primitives) {
    for (const [category, group] of Object.entries(tokens.primitives)) {
      for (const [key, token] of Object.entries(group)) {
        if (token && token.type === 'color' && token.value) {
          const jsonPath = `primitives.${category}.${key}`;
          const varName = buildPrimitiveVarName(category, key);
          const formattedVal = formatColorValue(token.value);
          primitiveMap.set(jsonPath, varName);
          primitiveDefs.push({ category, key, varName, value: formattedVal });
        }
      }
    }
  }

  // 3. Write Primitives Section
  lines.push('  /* ==========================================================================');
  lines.push('     1. PRIMITIVE PALETTES (DO NOT USE DIRECTLY IN UI)');
  lines.push('     These raw values feed the semantic color roles.');
  lines.push('     ========================================================================== */');

  let currentCategory = null;
  for (const item of primitiveDefs) {
    if (item.category !== currentCategory) {
      currentCategory = item.category;
      const title = currentCategory
        .split(' ')
        .map(w => w.charAt(0).toUpperCase() + w.slice(1))
        .join(' ');
      lines.push('', `  /* --- Primitives: ${title} --- */`);
    }
    lines.push(`  ${item.varName}: ${item.value};`);
  }

  // 4. Resolve and Write Color Roles
  lines.push('', '  /* ==========================================================================');
  lines.push('     2. COLOR ROLES (PUBLIC UI CONTRACT - USE THESE IN UI COMPONENTS)');
  lines.push('     Semantic roles mapped to primitives. Change themes by remapping these.');
  lines.push('     ========================================================================== */');

  const colorRoles = tokens['colour roles'] || {};
  const roleEntries = Object.entries(colorRoles);
  const unresolved = [];

  for (const [roleName, token] of roleEntries) {
    const roleVar = buildRoleVarName(roleName);
    let resolvedValue = token.value;

    if (typeof token.value === 'string' && token.value.startsWith('{') && token.value.endsWith('}')) {
      const refPath = token.value.slice(1, -1).trim();
      const targetVar = primitiveMap.get(refPath);
      if (targetVar) {
        resolvedValue = `var(${targetVar})`;
      } else {
        unresolved.push({ roleName, refPath });
        resolvedValue = `/* UNRESOLVED: ${token.value} */`;
      }
    }

    lines.push(`  ${roleVar}: ${resolvedValue};`);

    // Standard alias: provide --color-role-* alongside --color-*
    const roleAliasVar = roleVar.replace(/^--color-/, '--color-role-');
    if (roleAliasVar !== roleVar) {
      lines.push(`  ${roleAliasVar}: var(${roleVar});`);
    }

    // Fix typo fallback if present (e.g. 'on tertairy container' -> 'on-tertiary-container')
    if (roleName === 'on tertairy container') {
      lines.push(`  --color-on-tertiary-container: var(${roleVar});`);
      lines.push(`  --color-role-on-tertiary-container: var(${roleVar});`);
    }
  }

  if (unresolved.length > 0) {
    throw new Error(
      `Failed to resolve ${unresolved.length} token reference(s):\n` +
      unresolved.map(u => `  Role "${u.roleName}" -> "${u.refPath}"`).join('\n')
    );
  }

  // 5. Write Shadows / Effects
  if (tokens.effect && tokens.effect.shadow) {
    lines.push('', '  /* ==========================================================================');
    lines.push('     3. ELEVATION SHADOWS (EFFECTS)');
    lines.push('     ========================================================================== */');

    for (const [shadowName, token] of Object.entries(tokens.effect.shadow)) {
      if (token && token.value && token.value.shadowType === 'dropShadow') {
        const v = token.value;
        const color = formatColorValue(v.color);
        const shadowVal = `${v.offsetX}px ${v.offsetY}px ${v.radius}px ${v.spread}px ${color}`;
        lines.push(`  --shadow-${shadowName.toLowerCase()}: ${shadowVal};`);
      }
    }
  }

  // 6. Write Typography Variables
  const typographyUtilityClasses = [];

  if (tokens.typography) {
    lines.push('', '  /* ==========================================================================');
    lines.push('     4. TYPOGRAPHY TOKENS (MATERIAL DESIGN 3 TYPE SCALE)');
    lines.push('     ========================================================================== */');

    for (const [scaleGroup, sizes] of Object.entries(tokens.typography)) {
      for (const [size, props] of Object.entries(sizes)) {
        const prefix = `--typography-${scaleGroup.toLowerCase()}-${size.toLowerCase()}`;
        const fontSize = props.fontSize ? `${props.fontSize.value}px` : '16px';
        const lineHeight = props.lineHeight ? `${props.lineHeight.value}px` : 'normal';
        const fontWeight = props.fontWeight ? props.fontWeight.value : 'normal';
        const letterSpacing = props.letterSpacing ? `${props.letterSpacing.value}px` : 'normal';
        const fontFamily = props.fontFamily ? `"${props.fontFamily.value}", sans-serif` : 'sans-serif';

        lines.push(`  ${prefix}-font-family: ${fontFamily};`);
        lines.push(`  ${prefix}-font-size: ${fontSize};`);
        lines.push(`  ${prefix}-font-weight: ${fontWeight};`);
        lines.push(`  ${prefix}-line-height: ${lineHeight};`);
        lines.push(`  ${prefix}-letter-spacing: ${letterSpacing};`);

        typographyUtilityClasses.push(
          `.text-${scaleGroup.toLowerCase()}-${size.toLowerCase()} {\n` +
          `  font-family: var(${prefix}-font-family);\n` +
          `  font-size: var(${prefix}-font-size);\n` +
          `  font-weight: var(${prefix}-font-weight);\n` +
          `  line-height: var(${prefix}-line-height);\n` +
          `  letter-spacing: var(${prefix}-letter-spacing);\n` +
          `}`
        );
      }
    }
  }

  // Close :root
  lines.push('}', '');

  // 7. Append Typography Utility Classes
  if (typographyUtilityClasses.length > 0) {
    lines.push(
      '/* ==========================================================================',
      '   5. TYPOGRAPHY UTILITY CLASSES',
      '   Convenience classes for directly applying type styles to UI elements.',
      '   ========================================================================== */',
      ...typographyUtilityClasses,
      ''
    );
  }

  return {
    css: lines.join('\n'),
    stats: {
      primitivesCount: primitiveDefs.length,
      rolesCount: roleEntries.length,
      shadowsCount: Object.keys((tokens.effect && tokens.effect.shadow) || {}).length,
      typographyCount: typographyUtilityClasses.length,
    }
  };
}

/**
 * Main build function
 */
function buildTokens(inputFilePath, outputFilePath) {
  const resolvedInput = path.resolve(process.cwd(), inputFilePath || './design-tokens.tokens.json');
  const resolvedOutput = path.resolve(process.cwd(), outputFilePath || './styles/tokens.css');

  if (!fs.existsSync(resolvedInput)) {
    throw new Error(`Token file not found at: ${resolvedInput}`);
  }

  const raw = fs.readFileSync(resolvedInput, 'utf8');
  const tokens = JSON.parse(raw);

  const { css, stats } = convertTokensToCSS(tokens);

  const outDir = path.dirname(resolvedOutput);
  if (!fs.existsSync(outDir)) {
    fs.mkdirSync(outDir, { recursive: true });
  }

  fs.writeFileSync(resolvedOutput, css, 'utf8');

  return {
    inputPath: resolvedInput,
    outputPath: resolvedOutput,
    stats,
  };
}

// Execute when run directly from CLI
if (require.main === module) {
  const args = process.argv.slice(2);
  const inputArg = args[0] || './design-tokens.tokens.json';
  const outputArg = args[1] || './styles/tokens.css';

  console.log(`[build-tokens] Reading design tokens from: ${inputArg}`);
  try {
    const result = buildTokens(inputArg, outputArg);
    console.log(`[build-tokens] Successfully generated CSS variables!`);
    console.log(`[build-tokens] Output: ${result.outputPath}`);
    console.log(`[build-tokens] Summary:`);
    console.log(`  - Primitives (internal palette):   ${result.stats.primitivesCount} variables`);
    console.log(`  - Color Roles (UI semantic contract): ${result.stats.rolesCount} roles (+ aliases)`);
    console.log(`  - Shadows / Effects:               ${result.stats.shadowsCount} variables`);
    console.log(`  - Typography Styles:               ${result.stats.typographyCount} styles`);
  } catch (err) {
    console.error(`[build-tokens] Error:`, err.message);
    process.exit(1);
  }
}

module.exports = {
  buildTokens,
  convertTokensToCSS,
  buildPrimitiveVarName,
  buildRoleVarName,
  formatColorValue,
};

