/**
 * tests/tokens.test.js
 * 
 * Unit test suite for design token conversion script (scripts/build-tokens.js).
 * Verified against PRD Section 6 (UI Screens design system compliance)
 * and Section 8.3 (App shell lightweight styling architecture).
 */

const assert = require('assert');
const fs = require('fs');
const path = require('path');
const { convertTokensToCSS, buildTokens } = require('../scripts/build-tokens');

function runTests() {
  console.log('Running Design Tokens Conversion Tests...\n');

  const tokensPath = path.resolve(__dirname, '../design-tokens.tokens.json');
  assert.ok(fs.existsSync(tokensPath), 'design-tokens.tokens.json must exist');
  const tokens = JSON.parse(fs.readFileSync(tokensPath, 'utf8'));

  // Test 1: Core conversion produces valid CSS output
  const { css, stats } = convertTokensToCSS(tokens);
  assert.ok(css && typeof css === 'string', 'CSS output must be a string');
  assert.ok(css.includes(':root {'), 'CSS must declare :root selector');
  assert.ok(css.includes('DO NOT EDIT THIS FILE DIRECTLY'), 'CSS must include source of truth warning');
  console.log('  [PASS] Test 1: Generated CSS output structure is valid');

  // Test 2: Primitive Palette Extraction
  assert.strictEqual(stats.primitivesCount, 151, 'Must extract all 151 primitive color tokens');
  assert.ok(css.includes('--primitive-primary-40: #2563eb;'), 'Must correctly format primary40 primitive');
  assert.ok(css.includes('--primitive-primary-100: #ffffff;'), 'Must simplify 100% opacity hex to 6 digits');
  assert.ok(css.includes('--primitive-neutral-98:'), 'Must include neutral tonal scale');
  console.log('  [PASS] Test 2: All 151 primitive colors extracted and formatted');

  // Test 3: Color Roles (Public Semantic Layer)
  assert.strictEqual(stats.rolesCount, 50, 'Must extract all 50 color roles');
  assert.ok(css.includes('--color-primary: var(--primitive-primary-40);'), 'Primary role must reference primitive primary 40');
  assert.ok(css.includes('--color-on-primary: var(--primitive-primary-100);'), 'On-primary role must reference primitive primary 100');
  assert.ok(css.includes('--color-surface: var(--primitive-neutral-98);'), 'Surface role must reference primitive neutral 98');
  assert.ok(css.includes('--color-on-surface: var(--primitive-neutral-10);'), 'On-surface role must reference primitive neutral 10');
  assert.ok(css.includes('--color-outline: var(--primitive-neutral-variant-90);'), 'Outline role must reference primitive neutral variant 90');
  assert.ok(css.includes('--color-error: var(--primitive-error-40);'), 'Error role must reference primitive error 40');
  console.log('  [PASS] Test 3: Color roles correctly reference primitive CSS variables via var()');

  // Test 4: Role Aliases
  assert.ok(css.includes('--color-role-primary: var(--color-primary);'), 'Must provide --color-role-* alias');
  assert.ok(css.includes('--color-role-surface: var(--color-surface);'), 'Must provide --color-role-surface alias');
  assert.ok(css.includes('--color-on-tertiary-container:'), 'Must handle spelling correction for tertairy');
  console.log('  [PASS] Test 4: Role aliases (--color-role-*) and fallback corrections generated');

  // Test 5: No Unresolved References
  assert.ok(!css.includes('UNRESOLVED'), 'Must have zero unresolved token references');
  console.log('  [PASS] Test 5: Zero unresolved token references in the entire output');

  // Test 6: Elevation Shadows
  assert.strictEqual(stats.shadowsCount, 3, 'Must extract 3 shadow effect tokens');
  assert.ok(css.includes('--shadow-soft: 1px 4px 30px 0px #2563eb1f;'), 'Must format soft shadow correctly');
  assert.ok(css.includes('--shadow-medium: 4px 6px 24px 0px #2563eb2e;'), 'Must format medium shadow correctly');
  assert.ok(css.includes('--shadow-hard: 6px 10px 20px 0px #2563eb33;'), 'Must format hard shadow correctly');
  console.log('  [PASS] Test 6: Elevation shadows accurately translated to CSS box-shadow syntax');

  // Test 7: Typography Scale & Utility Classes
  assert.strictEqual(stats.typographyCount, 15, 'Must extract 15 typography styles (5 categories x 3 sizes)');
  assert.ok(css.includes('--typography-body-large-font-size: 16px;'), 'Must define body large font-size');
  assert.ok(css.includes('--typography-headline-small-line-height: 32px;'), 'Must define headline small line-height');
  assert.ok(css.includes('.text-body-large {'), 'Must generate .text-body-large utility class');
  console.log('  [PASS] Test 7: Typography scale variables and utility classes generated');

  // Test 8: End-to-End File Generation
  const outputPath = path.resolve(__dirname, '../styles/tokens.css');
  const result = buildTokens(tokensPath, outputPath);
  assert.ok(fs.existsSync(result.outputPath), 'Generated CSS file must exist on disk');
  const fileContent = fs.readFileSync(result.outputPath, 'utf8');
  assert.strictEqual(fileContent, css, 'File content on disk must match generated CSS');
  console.log('  [PASS] Test 8: End-to-end file generation writes exact expected CSS to disk');

  console.log('\nAll 8 token conversion tests passed successfully!');
}

try {
  runTests();
} catch (err) {
  console.error('\nTest failed:', err);
  process.exit(1);
}

